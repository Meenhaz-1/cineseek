function make(
  id,
  category,
  script,
  query,
  expectedIds,
  changes = {},
  extra = {},
) {
  const value = interpretation(query, changes);
  return {
    id,
    category,
    script,
    query,
    expectedIds,
    value,
    expected: {
      people: [],
      titleIds: [],
      genres: value.genres,
      genreMode: value.genreMode,
      filters: Object.fromEntries(
        Object.entries(value.filters).filter(([, v]) => v !== null),
      ),
      sort: value.sort,
      blocked: false,
      ...extra,
    },
  };
}
